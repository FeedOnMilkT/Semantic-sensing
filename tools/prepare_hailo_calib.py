#!/usr/bin/env python
"""Prepare ADE20K val calibration tensors for Hailo optimize() (B-arm §9.2).

Samples N images (default 512) from ADE20K validation, resizes to the deploy
square (default 512x512), and writes two layouts under the output directory:

  uint8_nhwc/     raw RGB uint8, NHWC — for models that bake normalization in .alls
  float32_nhwc/   ImageNet-normalized float32, NHWC — matches training forward

Also writes meta.json (counts, shapes, normalize recipe) and a tiny
load_calib.py helper for the Hailo suite container.

  python tools/prepare_hailo_calib.py --help
  python tools/prepare_hailo_calib.py --limit 8   # smoke
  python tools/prepare_hailo_calib.py             # full 512-set for level-2 optimize
"""
import argparse
import json
import os

from _common import pick_device  # noqa: F401
import numpy as np
import torch

from omegaconf import OmegaConf

from src.datasets import build_dataset

_DEFAULT_OUT = "/data/sidney/checkpoints/semantic-sensing/hailo/calib"
_MEAN = np.array([0.485, 0.456, 0.406], dtype=np.float32)
_STD = np.array([0.229, 0.224, 0.225], dtype=np.float32)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--limit", type=int, default=512,
                    help="number of val images (default 512; use 1024+ for Hailo level 2/4)")
    ap.add_argument("--size", type=int, nargs=2, default=[512, 512], help="H W deploy square")
    ap.add_argument("--out-dir", default=_DEFAULT_OUT)
    ap.add_argument("--start", type=int, default=0, help="val offset (reproducible subsample)")
    args = ap.parse_args()

    H, W = args.size
    ds = build_dataset(OmegaConf.create(dict(
        name="ade20k",
        args=dict(split="val", size=[H, W], augment=False,
                  num_classes=150, ignore_index=255),
    )))
    n = min(args.limit, len(ds) - args.start)
    assert n > 0, f"empty calib set (len={len(ds)}, start={args.start})"

    u8_dir = os.path.join(args.out_dir, "uint8_nhwc")
    f32_dir = os.path.join(args.out_dir, "float32_nhwc")
    os.makedirs(u8_dir, exist_ok=True)
    os.makedirs(f32_dir, exist_ok=True)

    indices = []
    for i in range(n):
        idx = args.start + i
        sample = ds[idx]
        # dataset returns NCHW normalized float
        chw = sample["image"].numpy().astype(np.float32)
        hwc_f32 = np.transpose(chw, (1, 2, 0))
        hwc_u8 = np.clip(hwc_f32 * _STD + _MEAN, 0.0, 1.0)
        hwc_u8 = (hwc_u8 * 255.0 + 0.5).astype(np.uint8)
        name = f"{i:05d}.npy"
        np.save(os.path.join(u8_dir, name), hwc_u8)
        np.save(os.path.join(f32_dir, name), hwc_f32)
        indices.append(idx)

    meta = dict(
        source="ade20k_val",
        hf_repo="merve/scene_parse_150",
        count=n,
        val_indices=indices,
        shape_nhwc=[H, W, 3],
        shape_nchw=[3, H, W],
        uint8_dir="uint8_nhwc",
        float32_dir="float32_nhwc",
        normalize=dict(
            recipe="(x/255 - mean) / std",
            mean=_MEAN.tolist(),
            std=_STD.tolist(),
            note="float32_nhwc already normalized; uint8_nhwc is raw RGB before normalize",
        ),
        hailo_hint=dict(
            layout="NHWC",
            recommended="float32_nhwc if ONNX input expects normalized tensor; "
                        "uint8_nhwc + normalization() in .alls otherwise",
            level2_min_images=1024,
        ),
    )
    with open(os.path.join(args.out_dir, "meta.json"), "w") as f:
        json.dump(meta, f, indent=2)

    helper = f'''"""Load calib tensors for Hailo runner.optimize() — generated by prepare_hailo_calib.py."""
import json
import os
import numpy as np

_ROOT = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(_ROOT, "meta.json")) as f:
    META = json.load(f)

def load_calib(kind="float32_nhwc", limit=None):
    """Return np.ndarray (N, H, W, 3) NHWC stack."""
    sub = META[kind if kind.endswith("_nhwc") else kind + "_nhwc"]
    d = os.path.join(_ROOT, sub)
    files = sorted(f for f in os.listdir(d) if f.endswith(".npy"))
    if limit:
        files = files[:limit]
    arrs = [np.load(os.path.join(d, f)) for f in files]
    return np.stack(arrs, axis=0)
'''
    with open(os.path.join(args.out_dir, "load_calib.py"), "w") as f:
        f.write(helper)

    print(f"== Hailo calib prepared: {n} images @ {H}x{W} ==")
    print(f"   out: {os.path.abspath(args.out_dir)}")
    print(f"   uint8_nhwc:   {u8_dir}  (e.g. 00000.npy)")
    print(f"   float32_nhwc: {f32_dir}")
    print(f"   meta.json + load_calib.py")
    print(f"   val index range: [{indices[0]} .. {indices[-1]}]")


if __name__ == "__main__":
    main()
